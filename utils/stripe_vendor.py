#!/usr/bin/env python3
"""Vendor a fivetran/dbt_stripe checkout into projects/p12_stripe.

Usage: utils/stripe_vendor.py <path to dbt_stripe checkout>

Re-running regenerates every vendored file (models/, macros/ except
macros/dagbench/) from the checkout. Files we own (dbt_project.yml,
profiles.yml, packages.yml, generate_data.py, load_postgres.py, tests/generic,
macros/dagbench/) are left alone. See projects/p12_stripe/VENDORED.md for the
list of transformations.
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
DST = REPO_ROOT / "projects" / "p12_stripe"
PROJECT = "p12_stripe"

# Source tables utils/stripe_data.py does not generate: we read `price` (not the
# legacy `plan`) and `subscription` (not `subscription_history`); see the
# stripe__using_price / stripe__using_subscription_history vars.
UNUSED_SOURCES = {"plan", "subscription_history"}

# The package's own macros, called as `stripe.<macro>(` and dispatched in the
# 'stripe' namespace. Source name ('stripe'), var names (stripe__*) and
# fivetran_utils' package_name='stripe' (a var prefix) are left alone.
PACKAGE_MACROS = ("convert_values", "does_table_exist", "select_metadata_columns", "date_timezone")

# Exact-text fixes to vendored models. Each must match exactly once.
#
# Upstream sizes its date spines from `current_date` and from run-time queries
# (dbt_utils.get_single_value, only under `dbt run/build`; `dbt compile` falls
# back to "last month to today"). Both make the compiled SQL depend on the day
# it is compiled and on how it is compiled. Pin them to the generated data's
# fixed window (vars dagbench_start_date / dagbench_as_of_date).
SPINE_BLOCK = re.compile(r"\{% if execute and flags\.WHICH in \('run', 'build'\) %\}.*?\{% endif %\}", re.S)
PATCHES = [
    ("models/intermediate/int_stripe__date_spine.sql", SPINE_BLOCK,
     "{# dag-bench: fixed window instead of the data's min date .. today #}\n"
     "    {% set first_date = \"cast('\" ~ var('dagbench_start_date') ~ \"' as date)\" %}\n"
     "    {% set last_date = \"cast('\" ~ var('dagbench_as_of_date') ~ \"' as date)\" %}"),
    ("models/stripe__subscription_item_mrr_report.sql", SPINE_BLOCK,
     "{# dag-bench: fixed window instead of the first item month .. this month #}\n"
     "{% set first_month = \"cast('\" ~ var('dagbench_start_date') ~ \"' as date)\" %}\n"
     "{% set last_month = dbt.date_trunc('month', \"cast('\" ~ var('dagbench_as_of_date') ~ \"' as date)\") %}"),
]
# "This month" in stripe__customer_overview is relative to the wall clock.
TEXT_REPLACEMENTS = [
    ("models/stripe__customer_overview.sql", "dbt.current_timestamp_backcompat()",
     "\"cast('\" ~ var('dagbench_as_of_date') ~ \"' as \" ~ dbt.type_timestamp() ~ \")\""),
]


def copy_tree(src: Path, dst: Path) -> None:
    for path in sorted(src.rglob("*")):
        if path.is_dir():
            continue
        out = dst / path.relative_to(src)
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, out)


def rename_package(path: Path) -> None:
    text = path.read_text()
    new = re.sub(r"\bstripe\.(" + "|".join(PACKAGE_MACROS) + r")\(", PROJECT + r".\1(", text)
    new = re.sub(r"(adapter\.dispatch\('[a-z_]+',\s*)'stripe'\)", r"\1'" + PROJECT + "')", new)
    if new != text:
        path.write_text(new)


def write_sources() -> None:
    """models/staging/src_stripe.yml -> models/sources.yml (where load_postgres.py
    looks), reading from the target schema like our other projects."""
    src_yml = DST / "models" / "staging" / "src_stripe.yml"
    data = yaml.safe_load(src_yml.read_text())
    (source,) = data["sources"]
    assert source["name"] == "stripe"
    source.pop("database", None)
    source["schema"] = "{{ 'main' if target.type == 'duckdb' else target.schema }}"
    source["config"]["enabled"] = True
    source["config"].pop("freshness", None)
    tables = []
    for table in source["tables"]:
        if table["name"] in UNUSED_SOURCES:
            continue
        table.pop("identifier", None)
        tables.append(table)
    source["tables"] = tables
    text = yaml.safe_dump(data, sort_keys=False, width=200, allow_unicode=True)
    (DST / "models" / "sources.yml").write_text(
        "# Generated by utils/stripe_vendor.py from models/staging/src_stripe.yml.\n"
        "# Raw tables written by generate_data.py.\n" + text
    )
    src_yml.unlink()


def apply_patches() -> None:
    for rel, pattern, replacement in PATCHES:
        path = DST / rel
        text, n = pattern.subn(lambda _: replacement, path.read_text())
        assert n == 1, (rel, pattern.pattern)
        path.write_text(text)
    for rel, old, new in TEXT_REPLACEMENTS:
        path = DST / rel
        text = path.read_text()
        assert old in text, (rel, old)
        path.write_text(text.replace(old, new))
    leftovers = [str(p.relative_to(DST)) for p in (DST / "models").rglob("*.sql")
                 if re.search(r"current_date|current_timestamp|get_single_value", p.read_text())]
    assert not leftovers, f"wall-clock / run-time queries left in {leftovers}"


def main() -> None:
    src = Path(sys.argv[1]).resolve()
    sha = subprocess.run(["git", "rev-parse", "HEAD"], cwd=src, check=True,
                         capture_output=True, text=True).stdout.strip()
    version = yaml.safe_load((src / "dbt_project.yml").read_text())["version"]

    for sub in ("models", "macros"):
        for child in (DST / sub).glob("*") if (DST / sub).exists() else []:
            if child.name == "dagbench":
                continue
            shutil.rmtree(child) if child.is_dir() else child.unlink()

    copy_tree(src / "models", DST / "models")
    copy_tree(src / "macros", DST / "macros")
    for path in list((DST / "models").rglob("*")) + list((DST / "macros").rglob("*")):
        if path.suffix in {".sql", ".yml"} and "dagbench" not in path.parts:
            rename_package(path)
    write_sources()
    apply_patches()
    (DST / "UPSTREAM").write_text(f"https://github.com/fivetran/dbt_stripe {version} {sha}\n")
    print(f"Vendored dbt_stripe {version} ({sha}) into {DST.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
